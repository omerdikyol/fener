#!/usr/bin/env python3
"""Builds the website's font subset and icon table from the icons the site uses.

Needs fonttools and brotli (pip install fonttools brotli) and JetBrains Mono Nerd Font installed
in ~/Library/Fonts. Writes site/icons.js and site/fonts/jbm-regular.woff2.
"""
import os, re, subprocess, sys

root = os.path.join(os.path.dirname(__file__), "..")
site = os.path.join(root, "site")
glyphs = {}
for line in open(os.path.join(root, "Sources/Fener/NerdGlyphs.swift"), encoding="utf-8"):
    parts = line.split()
    if len(parts) == 2 and re.fullmatch(r"[0-9a-f]{4,5}", parts[1]):
        glyphs[parts[0]] = parts[1]

used = set()
for name in ("index.html", "app.js"):
    used |= set(re.findall(r'"((?:md|fa)-[a-z0-9_]+)"', open(os.path.join(site, name), encoding="utf-8").read()))
missing = sorted(u for u in used if u not in glyphs)
if missing:
    sys.exit("unknown icons: " + ", ".join(missing))

with open(os.path.join(site, "icons.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build-site.py: Nerd Font icons used by the site (MIT, Nerd Fonts).\n")
    f.write("window.ICONS = {\n")
    for name in sorted(used):
        f.write(f'  "{name}": "\\u{{{glyphs[name]}}}",\n')
    f.write("};\n")

text = ("U+0020-007E,U+00A0-017F,U+2013-2014,U+2018-201D,U+2022,U+2026,U+2190-2193,U+2212,U+2318,"
        "U+2325,U+21E7,U+2303,U+23CE,U+238B,U+232B,U+20AC,U+00D7,U+00F7,U+00B0,U+203A")
icons = ",".join("U+" + glyphs[u] for u in sorted(used))
fonts = os.path.expanduser("~/Library/Fonts")
for weight, extra in (("Regular", "," + icons),):   # the page uses one weight of the mono
    subprocess.run(["pyftsubset", os.path.join(fonts, f"JetBrainsMonoNerdFont-{weight}.ttf"), f"--unicodes={text}{extra}",
                    "--flavor=woff2", "--layout-features=kern,liga,calt",
                    f"--output-file={os.path.join(site, 'fonts', 'jbm-' + weight.lower() + '.woff2')}"], check=True)
print(f"{len(used)} icons; wrote site/icons.js and site/fonts/*.woff2")
